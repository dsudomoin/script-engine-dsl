package io.github.dsudomoin.migration

/**
 * Политика обработки ошибки одного элемента стадии.
 *
 * Параметризована типом элемента, поэтому классификатор [Handle] видит свой `T`, а не `Any?`.
 *
 * Не распространяется на отказы асинхронных эффектов: к моменту, когда известен исход доставки,
 * элемент давно посчитан, и [Decision.Skip] для него физически неприменим. Любой такой отказ
 * валит стадию на барьере.
 */
sealed interface ItemError<in T> {

    /** Решение классификатора [Handle]. */
    enum class Decision { Skip, Fail }

    /** Ошибка элемента завершает стадию. Умолчание. */
    data object Fail : ItemError<Any?>

    /** Ошибка элемента аудитируется и пропускается, стадия продолжается. */
    data object Skip : ItemError<Any?>

    /** Решение принимает пользовательский классификатор, получающий типизированный элемент. */
    class Handle<T>(val decide: (Throwable, T) -> Decision) : ItemError<T>
}
