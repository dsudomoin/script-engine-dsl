package io.github.dsudomoin.migration.csv

/**
 * Квотинг CSV-ячейки по RFC 4180. Если значение содержит [delimiter], двойную кавычку, `\n`
 * или `\r` — оборачиваем в `"..."` и удваиваем внутренние `"` → `""`. Иначе возвращаем как есть.
 *
 * Разделитель — параметр, а не константа: при выводе через `;` порвала бы строку именно точка
 * с запятой, а запятая осталась бы обычным символом. Квотирование «на всякий случай» по обоим
 * раздувало бы файл кавычками там, где они ничего не значат.
 *
 * Используется и в [CsvOutput.row], и в аудиторе ошибок.
 */
internal fun csvEscape(s: String, delimiter: Char = ','): String {
    val needs = s.any { it == delimiter || it == '"' || it == '\n' || it == '\r' }
    return if (needs) "\"" + s.replace("\"", "\"\"") + "\"" else s
}
